def main() -> int:
    print("=" * 60)
    print("电信风控 API 冒烟测试 (50 条请求)")
    print("=" * 60)

    # 1. health
    h = _get("/health")
    print(f"[1] /health          status={h['status']} service={h['service']}")
    assert h["status"] == "ok" and h["service"] == "tele-risk"

    # 2. rules
    rules = _get("/api/rules?page=1&page_size=20")
    print(f"[2] /api/rules       total={rules['total']} (期望 15)")
    assert rules["total"] == 15, f"规则数应为 15, 实际 {rules['total']}"

    # 3. 50 次风控检查
    print("-" * 60)
    print(f"[3] 跑 {len(TEST_CASES)} 次 /api/risk/check ...")
    print("-" * 60)

    passed = 0
    failed = 0
    errors = 0
    decision_counts: dict[str, int] = {}
    rule_hit_counts: dict[str, int] = {}

    for i, (msisdn, evt, expect_decision, expect_rules, desc) in enumerate(TEST_CASES):
        source_id = f"smoke_{i+1:03d}"
        try:
            resp = _post("/api/risk/check", {
                "event_type": evt, "source_id": source_id, "msisdn": msisdn,
                "event_data": {"desc": desc},
            })
            decision = resp["decision"]
            hit_ids = [r["rule_id"] for r in resp["triggered_rules"]]
            decision_counts[decision] = decision_counts.get(decision, 0) + 1

            for rid in hit_ids:
                rule_hit_counts[rid] = rule_hit_counts.get(rid, 0) + 1

            ok = True
            if expect_decision and decision != expect_decision:
                ok = False
            for r in expect_rules:
                if r not in hit_ids:
                    ok = False

            status = "OK" if ok else "FAIL"
            if ok:
                passed += 1
            else:
                failed += 1

            print(f"  [{i+1:2d}] {msisdn} | {evt:<6} | {decision:<8} | "
                  f"hit={hit_ids or '-':<16} | {desc[:20]:<20} | {status}")

        except Exception as e:
            errors += 1
            failed += 1
            print(f"  [{i+1:2d}] {msisdn} | ERROR: {type(e).__name__}: {e}")

    print("=" * 60)
    print(f"[完成] 总计 {len(TEST_CASES)} 条 | 通过={passed} | 失败={failed} | 异常={errors}")
    print(f"[决策分布]", end="")
    for k, v in sorted(decision_counts.items(), key=lambda x: -x[1]):
        print(f"  {k}={v}", end="")
    print()
    print(f"[规则命中统计]", end="")
    for k, v in sorted(rule_hit_counts.items(), key=lambda x: -x[1]):
        print(f"  {k}={v}", end="")
    print()
    print("=" * 60)

    if failed > 0:
        print("[FAIL] 有断言未通过, 请检查上述详情")
        return 1
    print("[全部通过] 50 条请求覆盖 7 类风险 + 正常卡 ✓")
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except AssertionError as e:
        print(f"\n[FAIL] 断言失败: {e}")
        sys.exit(1)
    except Exception as e:
        print(f"\n[ERR] {type(e).__name__}: {e}")
        sys.exit(2)